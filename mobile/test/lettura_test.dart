/// Un flusso SSE salvato, mandato a pezzi di 200 byte (le lettere accentate si spezzano fra due pezzi).
RispostaFinta sse(String nome) {
  final byte = utf8.encode(File('test/fixtures/lettura/$nome').readAsStringSync());
  return RispostaFinta(
    200,
    pezzi: [for (var i = 0; i < byte.length; i += 200) byte.sublist(i, i + 200 > byte.length ? byte.length : i + 200)],
    intestazioni: const {
      'content-type': ['text/event-stream'],
    },
  );
}

/// Le risposte del rito: le fixture dell'API locale, l'intervista e le scelte in ordine.
AdattatoreFinto reteRito() {
  final rete = apiDaFixture();
  final passi = (fixture('intervista.json')! as List<Object?>).toList();
  final scelte = (fixture('scelte.json')! as List<Object?>).toList();
  var passo = 0;
  var scelta = 0;
  rete.risposte.addAll({
    '/spreads': (_) => RispostaFinta.fixture('lettura/stese_en.json'),
    '/disclaimer': (_) =>
        RispostaFinta.json({'testo': 'This is a tarot reading generated by an artificial intelligence.'}),
    '/me/decks': (_) => RispostaFinta.json({
      'deck_ids': [1],
    }),
    'POST /readings': (_) => RispostaFinta.fixture('lettura/apertura.json', stato: 201),
    'POST /readings/anonime': (_) => RispostaFinta.fixture('lettura/apertura.json', stato: 201),
    // Come il server: una risposta si salva e basta (`continua: false`), «basta» chiude col riassunto, una chiamata
    // senza risposta (la prima, o «un'altra domanda») dà la domanda successiva.
    'POST /readings/$idLettura/interview': (_) {
      final c = jsonDecode(rete.corpi.last ?? '{}') as Map<String, Object?>;
      if (c['basta'] == true) return RispostaFinta.json(passi.last);
      if (c['risposta'] != null) return RispostaFinta.json({'scelta': true});
      return RispostaFinta.json(passi[passo++ % passi.length]);
    },
    'POST /readings/$idLettura/fan': (_) => RispostaFinta.fixture('lettura/ventaglio.json'),
    'POST /readings/$idLettura/pick': (_) => RispostaFinta.json(scelte[scelta++ % scelte.length]),
    'POST /readings/$idLettura/reveal/1': (_) => sse('rivela_1.sse'),
    'POST /readings/$idLettura/reveal/2': (_) => sse('rivela_2.sse'),
    'POST /readings/$idLettura/reveal/3': (_) => sse('rivela_3.sse'),
    'POST /readings/$idLettura/synthesis': (_) => sse('sintesi.sse'),
  });
  return rete;
}

/// Il corpo JSON dell'ultima richiesta a [percorso].
Map<String, Object?> corpo(AdattatoreFinto rete, String percorso) {
  final i = rete.richieste.lastIndexWhere((r) => r.uri.path == percorso);
  return jsonDecode(rete.corpi[i]!) as Map<String, Object?>;
}

/// Tocca l'elemento premibile con l'etichetta [etichetta] (le carte del ventaglio si sovrappongono: il tocco va dato
/// a quella giusta, come fa un lettore di schermo).
void premi(WidgetTester tester, String etichetta) {
  final p = tester.widget<Premibile>(find.byWidgetPredicate((w) => w is Premibile && w.etichetta == etichetta));
  p.alTocco!();
}

/// Porta in vista il testo [testo] (la pagina del telefono è lunga) e lo tocca.
Future<void> tocca(WidgetTester tester, String testo) async {
  await tester.ensureVisible(find.text(testo).last);
  await tester.pump();
  await tester.tap(find.text(testo).last);
}

/// L'avvertenza: la casella «ho capito», poi «Ho capito, cominciamo».
Future<void> accetta(WidgetTester tester) async {
  await tester.tap(find.text('I understand that tarot has no scientific validity'));
  await tester.pump();
  await tester.tap(find.text('I understand, let us begin'));
}

/// Le ombre come le vuole il controllo finale di flutter_test (montaApp le accende per i golden).
void finisci() => debugDisableShadows = true;

Future<void> attendi(WidgetTester tester, [int ms = 0]) async {
  if (ms > 0) await tester.pump(Duration(milliseconds: ms));
  await assesta(tester);
}

